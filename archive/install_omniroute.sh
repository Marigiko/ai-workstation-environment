#!/usr/bin/env bash
set -euo pipefail

# ─────────────────────────────────────────────────────────────────────────────
# OmniRoute Install Script — passes all commands via env (no string interpolation)
# Reference: Hard Rule #13 from OmniRoute AGENTS.md
# ─────────────────────────────────────────────────────────────────────────────

generate_secret() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -base64 48
    elif command -v python3 >/dev/null 2>&1; then
        python3 -c 'import secrets; print(secrets.token_urlsafe(48))'
    else
        echo "ERROR: no openssl or python3 available to generate secrets" >&2
        exit 1
    fi
}

OMNIROUTE_VERSION="${OMNIROUTE_VERSION:-3.8.50}"
OMNIROUTE_PORT="${OMNIROUTE_PORT:-20128}"
OMNIROUTE_DATA_DIR="${OMNIROUTE_DATA_DIR:-$HOME/.omniroute}"
OMNIROUTE_JWT_SECRET="${OMNIROUTE_JWT_SECRET:-$(generate_secret)}"
OMNIROUTE_API_KEY_SECRET="${OMNIROUTE_API_KEY_SECRET:-$(generate_secret)}"
OMNIROUTE_INITIAL_PASSWORD="${OMNIROUTE_INITIAL_PASSWORD:-$(generate_secret)}"
ENABLE_SOCKS5_PROXY="${ENABLE_SOCKS5_PROXY:-true}"
ALLOW_PRIVATE_PROVIDER_URLS="${ALLOW_PRIVATE_PROVIDER_URLS:-true}"

CONTAINER_NAME="awe-omniroute"

# ── Install OmniRoute globally if not present ────────────────────────────────
if ! command -v omniroute &>/dev/null; then
    echo "Installing OmniRoute v${OMNIROUTE_VERSION}..."
    export NVM_DIR="${NVM_DIR:-$HOME/.nvm}"
    if [ -s "$NVM_DIR/nvm.sh" ]; then
        # shellcheck disable=SC1091
        source "$NVM_DIR/nvm.sh"
    fi
    if ! command -v npm &>/dev/null; then
        echo "ERROR: npm not found. Cannot install OmniRoute." >&2
        exit 1
    fi
    npm install -g omniroute@"${OMNIROUTE_VERSION}"
    echo "OmniRoute v${OMNIROUTE_VERSION} installed."
else
    echo "OmniRoute already installed: $(omniroute --version 2>/dev/null || echo 'unknown')"
fi

# ── Generate .env if not present ─────────────────────────────────────────────
ENV_FILE="${OMNIROUTE_DATA_DIR}/.env"
if [ ! -f "$ENV_FILE" ]; then
    mkdir -p "$OMNIROUTE_DATA_DIR"
    cat > "$ENV_FILE" <<EOF
# OmniRoute — Auto-generated by install_omniroute.sh
PORT=${OMNIROUTE_PORT}
DATA_DIR=${OMNIROUTE_DATA_DIR}
JWT_SECRET=${OMNIROUTE_JWT_SECRET}
API_KEY_SECRET=${OMNIROUTE_API_KEY_SECRET}
INITIAL_PASSWORD=${OMNIROUTE_INITIAL_PASSWORD}
NODE_ENV=production
ENABLE_SOCKS5_PROXY=${ENABLE_SOCKS5_PROXY}
ALLOW_PRIVATE_PROVIDER_URLS=${ALLOW_PRIVATE_PROVIDER_URLS}
NEXT_PUBLIC_BASE_URL=http://localhost:${OMNIROUTE_PORT}
BASE_URL=http://localhost:${OMNIROUTE_PORT}
EOF
    echo ".env generated at ${ENV_FILE}"
fi

# ── Start OmniRoute ──────────────────────────────────────────────────────────
if [ -f "$OMNIROUTE_DATA_DIR/.pid" ] && kill -0 "$(cat "$OMNIROUTE_DATA_DIR/.pid" 2>/dev/null)" 2>/dev/null; then
    echo "OmniRoute is already running on port ${OMNIROUTE_PORT}"
    exit 0
fi

echo "Starting OmniRoute on port ${OMNIROUTE_PORT}..."
export OMNIROUTE_JWT_SECRET
export OMNIROUTE_API_KEY_SECRET
export OMNIROUTE_INITIAL_PASSWORD
export OMNIROUTE_PORT
export OMNIROUTE_DATA_DIR
export ENABLE_SOCKS5_PROXY
export ALLOW_PRIVATE_PROVIDER_URLS

omniroute launch --port "${OMNIROUTE_PORT}" --data-dir "${OMNIROUTE_DATA_DIR}" &
OMNIROUTE_PID=$!
echo "$OMNIROUTE_PID" > "$OMNIROUTE_DATA_DIR/.pid"
echo "OmniRoute started with PID ${OMNIROUTE_PID}"

# ── Verify ───────────────────────────────────────────────────────────────────
sleep 3
if curl -s "http://localhost:${OMNIROUTE_PORT}/v1/models" > /dev/null 2>&1; then
    echo "OmniRoute verified at http://localhost:${OMNIROUTE_PORT}/v1/models"
else
    echo "WARNING: OmniRoute may not be ready yet. Check logs." >&2
fi

echo "OmniRoute installation complete."
